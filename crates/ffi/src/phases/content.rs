//! C-ABI Foreign Function Interface for Gateway Phase 2: HTTP Content Phase.
//!
//! Generates immediate response payloads without forwarding to upstreams.
//! Powers direct endpoints such as `/metrics`, `/healthz`, and custom gateway endpoints
//! in a purely phase-driven, plugin-agnostic manner.

use std::{
    panic::{AssertUnwindSafe, catch_unwind},
    ptr, slice,
};

/// Incoming HTTP request metadata for Content Phase generation.
#[repr(C)]
pub struct AuroraContentInput {
    pub host: *const u8,
    pub host_len: usize,
    pub path: *const u8,
    pub path_len: usize,
    pub method: *const u8,
    pub method_len: usize,
    pub query: *const u8,
    pub query_len: usize,
}

/// Output response payload generated by Phase 2 Content.
#[repr(C)]
pub struct AuroraContentOutcome {
    pub status_code: u32,
    pub content_type_len: u32,
    pub content_type: [u8; 64],
    pub body_len: u32,
    pub body: *mut u8,
    pub body_cap: usize,
}

#[inline(always)]
unsafe fn slice_from_raw<'a>(ptr: *const u8, len: usize) -> &'a [u8] {
    if ptr.is_null() || len == 0 {
        &[]
    } else {
        unsafe { slice::from_raw_parts(ptr, len) }
    }
}

/// Executes Gateway Phase 2: HTTP Content Phase.
///
/// # Safety
/// `input` and `out_outcome` must point to valid initialized structs.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn aurora_gateway_phase_content(
    input: *const AuroraContentInput,
    out_outcome: *mut AuroraContentOutcome,
) -> u32 {
    if input.is_null() || out_outcome.is_null() {
        return 1;
    }

    let in_ref = unsafe { &*input };
    let out_ref = unsafe { &mut *out_outcome };

    let _ = catch_unwind(AssertUnwindSafe(|| {
        let path = unsafe { slice_from_raw(in_ref.path, in_ref.path_len) };

        if path.starts_with(b"/metrics") {
            let in_flight = aurora_engine::metrics::get_in_flight();
            let engine = aurora_extensions::get_prometheus_engine();
            let bytes = engine.render_scrape(in_flight);

            out_ref.status_code = 200;
            let ct = b"text/plain; version=0.0.4; charset=utf-8";
            out_ref.content_type_len = ct.len() as u32;
            out_ref.content_type[..ct.len()].copy_from_slice(ct);

            let to_copy = bytes.len().min(out_ref.body_cap);
            if !out_ref.body.is_null() && to_copy > 0 {
                unsafe {
                    ptr::copy_nonoverlapping(bytes.as_ptr(), out_ref.body, to_copy);
                }
            }
            out_ref.body_len = bytes.len() as u32;
        } else if path.starts_with(b"/healthz") {
            out_ref.status_code = 200;
            let ct = b"application/json";
            out_ref.content_type_len = ct.len() as u32;
            out_ref.content_type[..ct.len()].copy_from_slice(ct);

            let body = b"{\"status\":\"UP\"}\n";
            let to_copy = body.len().min(out_ref.body_cap);
            if !out_ref.body.is_null() && to_copy > 0 {
                unsafe {
                    ptr::copy_nonoverlapping(body.as_ptr(), out_ref.body, to_copy);
                }
            }
            out_ref.body_len = body.len() as u32;
        } else {
            out_ref.status_code = 404;
            let ct = b"text/plain";
            out_ref.content_type_len = ct.len() as u32;
            out_ref.content_type[..ct.len()].copy_from_slice(ct);
            out_ref.body_len = 0;
        }
    }));

    0
}
