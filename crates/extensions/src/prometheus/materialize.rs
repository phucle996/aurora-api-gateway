//! Prometheus Metrics Extension Materializer.
//!
//! Generates a dedicated, isolated NGINX internal management server block inside
//! `active-extensions-http.conf`. The port and allowed scraper IPs/CIDRs are 100%
//! dynamically configured via the extension spec. Zero ports or locations are
//! opened if this extension is omitted or disabled.

use serde_json::{Map, Value};
use std::net::IpAddr;
use std::str::FromStr;

pub fn materialize(
    instance_id: &str,
    config: &Map<String, Value>,
    http: &mut String,
    has_http: &mut bool,
    metrics_instances: &mut usize,
) -> Result<(), String> {
    *metrics_instances += 1;
    if *metrics_instances > 1 {
        return Err(
            "NodeSpec contains more than one prometheus/agent-metrics extension".to_string(),
        );
    }

    // Check if enabled (either root 'enabled' or 'prometheus.enabled')
    let enabled = config.get("enabled").and_then(Value::as_bool)
        .or_else(|| config.get("prometheus").and_then(Value::as_object).and_then(|p| p.get("enabled").and_then(Value::as_bool)))
        .unwrap_or(true);

    if !enabled {
        return Ok(());
    }

    // 1. Port resolution (mandatory, 1024..=65535)
    let port = config.get("port").and_then(Value::as_u64)
        .or_else(|| config.get("prometheus").and_then(Value::as_object).and_then(|p| p.get("port").and_then(Value::as_u64)))
        .ok_or_else(|| {
            format!(
                "prometheus extension instance '{instance_id}' requires 'port' to be explicitly configured"
            )
        })?;

    if !(1024..=65535).contains(&port) {
        return Err(format!(
            "prometheus extension instance '{instance_id}' port {port} is out of range (must be 1024-65535)"
        ));
    }

    // 2. Path resolution (defaults to /metrics)
    let path = config.get("path").and_then(Value::as_str)
        .or_else(|| config.get("prometheus").and_then(Value::as_object).and_then(|p| p.get("path").and_then(Value::as_str)))
        .unwrap_or("/metrics");

    if !path.starts_with('/') || path.contains([' ', ';', '{', '}', '\r', '\n', '\0']) {
        return Err(format!(
            "prometheus extension instance '{instance_id}' path '{path}' is invalid"
        ));
    }

    // 3. Allowlist resolution (mandatory: explicit list of allowed CIDRs/IPs)
    let allowlist_val = config
        .get("allowlist")
        .or_else(|| config.get("allowed_cidrs"))
        .or_else(|| {
            config.get("prometheus").and_then(Value::as_object)
                .and_then(|p| p.get("allowlist").or_else(|| p.get("allowed_cidrs")))
        });

    let allowlist = match allowlist_val {
        Some(Value::Array(arr)) => {
            let mut list = Vec::new();
            for item in arr {
                if let Some(s) = item.as_str() {
                    list.push(s.trim().to_string());
                } else {
                    return Err(format!(
                        "prometheus extension instance '{instance_id}' allowlist entries must be strings"
                    ));
                }
            }
            list
        }
        _ => Vec::new(),
    };

    if allowlist.is_empty() {
        return Err(format!(
            "prometheus extension instance '{instance_id}' requires non-empty 'allowlist' specifying allowed Prometheus scraper IPs or CIDRs"
        ));
    }

    // Validate each entry in allowlist
    let mut allow_directives = Vec::new();
    let mut has_allow_all = false;

    for entry in &allowlist {
        if entry == "all" || entry == "0.0.0.0/0" || entry == "::/0" {
            has_allow_all = true;
            allow_directives.push("allow all;".to_string());
            break;
        }

        if IpAddr::from_str(entry).is_ok() || ipnet::IpNet::from_str(entry).is_ok() {
            allow_directives.push(format!("allow {entry};"));
        } else {
            return Err(format!(
                "prometheus extension instance '{instance_id}' allowlist entry '{entry}' is not a valid IP or CIDR"
            ));
        }
    }

    // Render NGINX server block into active-extensions-http.conf
    http.push_str(&format!(
        "\n# Generated by Prometheus Extension: {instance_id}\nserver {{\n    listen {port};\n    server_name _;\n\n"
    ));

    for dir in &allow_directives {
        http.push_str(&format!("    {dir}\n"));
    }

    if !has_allow_all {
        http.push_str("    deny all;\n");
    }

    http.push_str(&format!(
        "\n    location = {path} {{\n        gateway_metrics;\n    }}\n}}\n"
    ));

    *has_http = true;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_prometheus_materialize() {
        let mut http = String::new();
        let mut has_http = false;
        let mut count = 0;
        let config: Map<String, Value> = serde_json::from_str(r#"{
            "port": 9145,
            "allowlist": ["127.0.0.1", "10.0.0.0/8"]
        }"#).unwrap();

        materialize("prom-1", &config, &mut http, &mut has_http, &mut count).unwrap();
        assert!(has_http);
        assert!(http.contains("listen 9145;"));
        assert!(http.contains("allow 127.0.0.1;"));
        assert!(http.contains("allow 10.0.0.0/8;"));
        assert!(http.contains("location = /metrics {"));
    }
}
