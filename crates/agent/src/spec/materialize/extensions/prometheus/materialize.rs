//! Prometheus Metrics Extension Materializer
//!
//! Generates a dedicated, isolated NGINX internal management server block inside
//! `active-extensions-http.conf`. The port and allowed scraper IPs/CIDRs are 100%
//! dynamically configured via the extension spec. Zero ports or locations are
//! opened if this extension is omitted or disabled.

use crate::spec::materialize::extensions::ExtensionInstanceSpec;
use crate::spec::materialize::extensions::common::{boolean, object, string, unsigned};
use serde_json::{Map, Value};
use std::net::IpAddr;
use std::str::FromStr;

pub fn materialize(
    instance: &ExtensionInstanceSpec,
    config: &Map<String, Value>,
    http: &mut String,
    has_http: &mut bool,
    metrics_instances: &mut usize,
) -> Result<(), String> {
    *metrics_instances += 1;
    if *metrics_instances > 1 {
        return Err(
            "NodeSpec contains more than one prometheus/agent-metrics extension".to_string(),
        );
    }

    // Check if enabled (either root 'enabled' or 'prometheus.enabled')
    let enabled = boolean(config, "enabled")
        .or_else(|| object(config, "prometheus").and_then(|p| boolean(p, "enabled")))
        .unwrap_or(true);

    if !enabled {
        return Ok(());
    }

    // 1. Port resolution (mandatory, 1024..=65535)
    let port = unsigned(config, "port")
        .or_else(|| object(config, "prometheus").and_then(|p| unsigned(p, "port")))
        .ok_or_else(|| {
            format!(
                "prometheus extension instance '{}' requires 'port' to be explicitly configured",
                instance.instance_id
            )
        })?;

    if !(1024..=65535).contains(&port) {
        return Err(format!(
            "prometheus extension instance '{}' port {} is out of range (must be 1024-65535)",
            instance.instance_id, port
        ));
    }

    // 2. Path resolution (defaults to /metrics)
    let path = string(config, "path")
        .or_else(|| object(config, "prometheus").and_then(|p| string(p, "path")))
        .unwrap_or("/metrics");

    if !path.starts_with('/') || path.contains([' ', ';', '{', '}', '\r', '\n', '\0']) {
        return Err(format!(
            "prometheus extension instance '{}' path '{}' is invalid",
            instance.instance_id, path
        ));
    }

    // 3. Allowlist resolution (mandatory: explicit list of allowed CIDRs/IPs)
    let allowlist_val = config
        .get("allowlist")
        .or_else(|| config.get("allowed_cidrs"))
        .or_else(|| {
            object(config, "prometheus")
                .and_then(|p| p.get("allowlist").or_else(|| p.get("allowed_cidrs")))
        });

    let allowlist = match allowlist_val {
        Some(Value::Array(arr)) => {
            let mut list = Vec::new();
            for item in arr {
                if let Some(s) = item.as_str() {
                    list.push(s.trim().to_string());
                } else {
                    return Err(format!(
                        "prometheus extension instance '{}' allowlist entries must be strings",
                        instance.instance_id
                    ));
                }
            }
            list
        }
        _ => Vec::new(),
    };

    if allowlist.is_empty() {
        return Err(format!(
            "prometheus extension instance '{}' requires non-empty 'allowlist' specifying allowed Prometheus scraper IPs or CIDRs",
            instance.instance_id
        ));
    }

    // Validate each entry in allowlist
    let mut allow_directives = Vec::new();
    let mut has_allow_all = false;

    for entry in &allowlist {
        if entry == "all" || entry == "0.0.0.0/0" || entry == "::/0" {
            has_allow_all = true;
            allow_directives.push("allow all;".to_string());
            break;
        }

        if IpAddr::from_str(entry).is_ok() || ipnet::IpNet::from_str(entry).is_ok() {
            allow_directives.push(format!("allow {};", entry));
        } else {
            return Err(format!(
                "prometheus extension instance '{}' allowlist entry '{}' is not a valid IP or CIDR",
                instance.instance_id, entry
            ));
        }
    }

    // Render NGINX server block into active-extensions-http.conf
    http.push_str(&format!(
        "\n# Generated by Prometheus Extension: {}\nserver {{\n    listen {};\n    server_name _;\n\n",
        instance.instance_id, port
    ));

    for dir in &allow_directives {
        http.push_str(&format!("    {}\n", dir));
    }

    if !has_allow_all {
        http.push_str("    deny all;\n");
    }

    http.push_str(&format!(
        "\n    location = {} {{\n        gateway_metrics;\n    }}\n}}\n",
        path
    ));

    *has_http = true;
    Ok(())
}
