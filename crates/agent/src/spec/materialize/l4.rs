use crate::spec::l4::L4Spec;
use ipnet::IpNet;
use std::collections::HashSet;

/// Generates NGINX stream block configuration for L4 stream proxying and CIDR access control.
pub fn generate_l4_streams_conf(l4: &Option<L4Spec>) -> Result<String, String> {
    let mut buf = String::from("# Generated by Aurora Dataplane Agent for L4 Stream Proxying\n");
    let l4_spec = match l4 {
        Some(spec) => spec,
        None => {
            buf.push_str("# No active L4 stream configuration\n");
            return Ok(buf);
        }
    };

    if l4_spec.upstreams.is_empty() && l4_spec.services.is_empty() {
        buf.push_str("# No active L4 stream configuration\n");
        return Ok(buf);
    }

    // 1. Upstreams
    for up in &l4_spec.upstreams {
        buf.push_str(&format!("upstream l4_{} {{\n", up.name));
        buf.push_str(&format!("    zone aurora_l4_{} 64k;\n", up.name));
        if up.algorithm == "least_conn" {
            buf.push_str("    least_conn;\n");
        // The control-plane calls its client-affinity algorithm `ip_hash`.
        // NGINX stream has no `ip_hash` directive, so materialize it as a
        // consistent hash of the client address. Keep `hash` for already
        // persisted NodeSpecs from earlier revisions.
        } else if up.algorithm == "ip_hash" || up.algorithm == "hash" {
            buf.push_str("    hash $remote_addr consistent;\n");
        }
        for s in &up.servers {
            let mut line = format!("    server {}", s.addr);
            if s.weight > 1 {
                line.push_str(&format!(" weight={}", s.weight));
            }
            if let Some(mf) = s.max_fails {
                line.push_str(&format!(" max_fails={}", mf));
            }
            if let Some(ref ft) = s.fail_timeout {
                line.push_str(&format!(" fail_timeout={}", ft));
            }
            if s.backup {
                line.push_str(" backup");
            }
            line.push_str(" resolve;\n");
            buf.push_str(&line);
        }
        buf.push_str("}\n\n");
    }

    // 2. Services
    for svc in &l4_spec.services {
        if !svc.enabled {
            continue;
        }
        buf.push_str("server {\n");
        let listen_opt = if svc.protocol.to_lowercase() == "udp" {
            " udp"
        } else {
            ""
        };
        buf.push_str(&format!("    listen {}{};\n", svc.listen_port, listen_opt));

        let mut acl_rules = svc.acl.clone();
        acl_rules.sort_by_key(|rule| std::cmp::Reverse(rule.priority));
        let mut priorities = HashSet::with_capacity(acl_rules.len());
        for acl in &acl_rules {
            if acl.priority == 0 || acl.priority > 1_000_000 {
                return Err(format!(
                    "L4 service {:?} has an invalid ACL priority {}",
                    svc.name, acl.priority
                ));
            }
            if !priorities.insert(acl.priority) {
                return Err(format!(
                    "L4 service {:?} has duplicate ACL priority {}",
                    svc.name, acl.priority
                ));
            }
            let action = acl.action.to_lowercase();
            if action != "allow" && action != "deny" {
                return Err(format!(
                    "L4 service {:?} has an invalid ACL action {:?}",
                    svc.name, acl.action
                ));
            }
            acl.cidr.parse::<IpNet>().map_err(|error| {
                format!(
                    "L4 service {:?} has an invalid ACL CIDR {:?}: {error}",
                    svc.name, acl.cidr
                )
            })?;
            buf.push_str(&format!("    {} {};\n", action, acl.cidr));
        }

        let is_endpoint = svc.forward_target_type.as_deref() == Some("endpoint")
            || (svc.upstream.trim().is_empty()
                && svc
                    .endpoint
                    .as_deref()
                    .map(|e| !e.trim().is_empty())
                    .unwrap_or(false));

        let is_l7_http_pipeline = is_endpoint
            && svc.protocol.eq_ignore_ascii_case("tcp")
            && svc
                .endpoint
                .as_deref()
                .map(|endpoint| endpoint.trim() == "127.0.0.1:80")
                .unwrap_or(false);

        let is_l7_tls_pipeline = is_endpoint
            && svc.protocol.eq_ignore_ascii_case("tcp")
            && svc
                .endpoint
                .as_deref()
                .map(|endpoint| endpoint.trim() == "127.0.0.1:9443")
                .unwrap_or(false);

        if is_l7_http_pipeline {
            // The internal HTTP bridge restores the client address from this PROXY header
            // before forwarding to the domain routing servers.
            buf.push_str("    proxy_protocol on;\n");
            buf.push_str("    proxy_pass 127.0.0.1:9082;\n");
        } else if is_l7_tls_pipeline {
            // The TLS bridge terminates HTTPS after reading PROXY protocol, so
            // the L7 access engine receives the original stream client IP.
            buf.push_str("    proxy_protocol on;\n");
            buf.push_str("    proxy_pass 127.0.0.1:9443;\n");
        } else if is_endpoint {
            if let Some(ref ep) = svc.endpoint {
                buf.push_str(&format!("    proxy_pass {};\n", ep.trim()));
            }
        } else if !svc.upstream.trim().is_empty() {
            buf.push_str(&format!("    proxy_pass l4_{};\n", svc.upstream.trim()));
        }
        if let Some(ref pt) = svc.proxy_timeout
            && !pt.trim().is_empty()
        {
            buf.push_str(&format!("    proxy_timeout {};\n", pt));
        }
        if let Some(ref pct) = svc.proxy_connect_timeout
            && !pct.trim().is_empty()
        {
            buf.push_str(&format!("    proxy_connect_timeout {};\n", pct));
        }
        buf.push_str("}\n\n");
    }

    Ok(buf)
}
